import type { NextConfig } from "next";

/**
 * Header keamanan (audit F-04) dan `poweredByHeader: false` (audit F-12).
 *
 * CSP sengaja memakai `'unsafe-inline'` untuk script: Next menyuntikkan inline
 * bootstrap/RSC payload, dan nonce per-request belum dipasang. Lapisan yang
 * tetap bernilai di sini adalah `frame-ancestors`/`object-src`/`base-uri` serta
 * penolakan sumber daya pihak ketiga — bukan proteksi XSS inline.
 */
const CSP = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "style-src 'self' 'unsafe-inline'",
  "script-src 'self' 'unsafe-inline'",
  "connect-src 'self'",
].join("; ");

const SECURITY_HEADERS = [
  { key: "Content-Security-Policy", value: CSP },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "same-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
  { key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains" },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: SECURITY_HEADERS }];
  },
};

export default nextConfig;
